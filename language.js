function showNotification(key, extraMessage = "") {

  const language =
    localStorage.getItem("siteLanguage") || "id";

  const notification =
    notificationTranslations[key];

  if (!notification) {
    return;
  }

  const message =
    language === "en"
      ? notification.en
      : notification.id;

  // Hapus notifikasi lama jika masih ada
  const oldNotification =
    document.querySelector(
      "#kerjivaNotification"
    );

  if (oldNotification) {
    oldNotification.remove();
  }

  // Buat notifikasi
  const notificationBox =
    document.createElement("div");

  notificationBox.id =
    "kerjivaNotification";

  notificationBox.className =
    "kerjiva-notification";

  notificationBox.textContent =
    message + extraMessage;

  document.body.appendChild(
    notificationBox
  );

  // Munculkan dengan efek halus
  requestAnimationFrame(() => {
    notificationBox.classList.add("show");
  });

  // Hilang otomatis
  setTimeout(() => {

    notificationBox.classList.remove(
      "show"
    );

    setTimeout(() => {
      notificationBox.remove();
    }, 300);

  }, 2500);

}
